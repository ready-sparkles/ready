import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import ts from "typescript";

const source = new URL("../../../../shared/domain/calendar-description.ts", import.meta.url);
const output = new URL("../../../public/outlook/calendar-description.js", import.meta.url);

/** Transpile the shared formatter and apply the repository Prettier style so the artifact stays lint-clean. */
export async function compiledFormatter() {
	const transpiled = `// Generated by web/adapters/primary/outlook/build-formatter.mjs. Edit shared/domain/calendar-description.ts.\n${
		ts.transpileModule(readFileSync(source, "utf8"), {
			compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020 },
		}).outputText
	}`;
	const filepath = fileURLToPath(output);
	const config = await resolveConfig(filepath);

	return format(transpiled, { ...config, filepath });
}
if (process.argv.includes("--write")) {
	writeFileSync(output, await compiledFormatter());
}
